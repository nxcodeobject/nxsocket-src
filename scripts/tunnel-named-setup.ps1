# Named Tunnel Cloudflare — domain TETAP untuk NxSocket
#
# Prasyarat:
#   - Akun Cloudflare + domain sudah di Cloudflare (DNS)
#   - nxsocket server jalan di PC (HTTP lokal:7080)
#   - cloudflared di tools/cloudflared/
#
# Setup sekali (interaktif, buka browser login):
#   powershell -File scripts/tunnel-named-setup.ps1 -Hostname nxsocket.domainanda.com
#
# Tiap hari jalanin tunnel:
#   powershell -File scripts/tunnel-named.ps1
#   atau: npm run tunnel:named

param(
  [Parameter(Mandatory = $true)]
  [string]$Hostname,
  [string]$TunnelName = "nxsocket"
)

$ErrorActionPreference = "Stop"
$Root = Split-Path -Parent $PSScriptRoot
$Exe = Join-Path $Root "tools\cloudflared\cloudflared-windows-amd64.exe"
$CfDir = Join-Path $env:USERPROFILE ".cloudflared"
$Example = Join-Path $Root "tools\cloudflared\config.example.yml"

if (-not (Test-Path $Exe)) {
  Write-Host "Mengunduh cloudflared..."
  New-Item -ItemType Directory -Force -Path (Split-Path $Exe) | Out-Null
  Invoke-WebRequest -Uri "https://github.com/cloudflare/cloudflared/releases/latest/download/cloudflared-windows-amd64.exe" -OutFile $Exe -UseBasicParsing
}

New-Item -ItemType Directory -Force -Path $CfDir | Out-Null

Write-Host ""
Write-Host "=== 1) Login Cloudflare (browser) ==="
Write-Host "Pilih zona/domain yang akan dipakai untuk $Hostname"
& $Exe tunnel login
if ($LASTEXITCODE -ne 0) { throw "Login gagal" }

Write-Host ""
Write-Host "=== 2) Buat tunnel '$TunnelName' (skip jika sudah ada) ==="
$existing = & $Exe tunnel list 2>&1 | Out-String
if ($existing -notmatch [regex]::Escape($TunnelName)) {
  & $Exe tunnel create $TunnelName
} else {
  Write-Host "Tunnel '$TunnelName' sudah ada."
}

Write-Host ""
Write-Host "=== 3) DNS route: $Hostname → tunnel ==="
& $Exe tunnel route dns $TunnelName $Hostname

# Ambil tunnel id dari list
$list = & $Exe tunnel list --output json 2>$null
$tunnelId = $null
if ($list) {
  try {
    $arr = $list | ConvertFrom-Json
    $hit = $arr | Where-Object { $_.name -eq $TunnelName } | Select-Object -First 1
    if ($hit) { $tunnelId = $hit.id }
  } catch { }
}
if (-not $tunnelId) {
  # fallback parse teks
  $line = (& $Exe tunnel list 2>&1 | Out-String) -split "`n" | Where-Object { $_ -match $TunnelName } | Select-Object -First 1
  if ($line -match '([0-9a-f]{8}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{12})') {
    $tunnelId = $Matches[1]
  }
}
if (-not $tunnelId) {
  throw "Tidak bisa baca Tunnel ID. Jalankan: cloudflared tunnel list"
}

$cred = Join-Path $CfDir "$tunnelId.json"
if (-not (Test-Path $cred)) {
  throw "Credentials tidak ketemu: $cred"
}

$configPath = Join-Path $CfDir "config.yml"
@"
# Generated by scripts/tunnel-named-setup.ps1 — NxSocket
tunnel: $tunnelId
credentials-file: $cred

ingress:
  - hostname: $Hostname
    service: http://127.0.0.1:7080
  - service: http_status:404
"@ | Set-Content -Path $configPath -Encoding utf8

$meta = Join-Path $Root "data\named-tunnel.json"
New-Item -ItemType Directory -Force -Path (Split-Path $meta) | Out-Null
@{
  hostname = $Hostname
  tunnelName = $TunnelName
  tunnelId = $tunnelId
  config = $configPath
  url = "https://$Hostname"
} | ConvertTo-Json | Set-Content -Path $meta -Encoding utf8

Set-Content -Path (Join-Path $Root "data\current-tunnel-url.txt") -Value "https://$Hostname" -Encoding utf8

Write-Host ""
Write-Host "=== SELESAI SETUP ==="
Write-Host "  Domain tetap : https://$Hostname"
Write-Host "  Config       : $configPath"
Write-Host "  Contoh config: $Example"
Write-Host ""
Write-Host "Jalankan tiap hari:"
Write-Host "  1) nxsocket server"
Write-Host "  2) npm run tunnel:named"
Write-Host ""
Write-Host "Di HP:"
Write-Host "  https://$Hostname/v1/demo5"
Write-Host ""
